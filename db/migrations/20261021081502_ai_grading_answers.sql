CREATE TABLE IF NOT EXISTS answers (
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id integer NOT NULL REFERENCES submissions(id) ON DELETE CASCADE,
 question_id integer NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
 extracted_text text,
 ai_score integer,
 ai_feedback text,
 ai_strengths jsonb,
 ai_lackings jsonb,
 ai_suggestions jsonb,
 teacher_score integer,
 teacher_feedback text,
 is_approved boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT uq_answers_submission_question UNIQUE (submission_id, question_id)
);
CREATE INDEX IF NOT EXISTS ix_answers_submission ON answers (submission_id);
CREATE INDEX IF NOT EXISTS ix_answers_question ON answers (question_id);
