CREATE TABLE IF NOT EXISTS submissions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id integer NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  content_text text,
  pdf_path varchar(512),
  original_filename varchar(255),
  mime_type varchar(100),
  file_size integer,
  status varchar(50) NOT NULL DEFAULT 'submitted',
  submitted_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT submissions_content_or_pdf CHECK (content_text IS NOT NULL OR pdf_path IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_submissions_assignment_student ON submissions (assignment_id, student_id);
CREATE INDEX IF NOT EXISTS ix_submissions_student ON submissions (student_id);
